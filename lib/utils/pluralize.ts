/**
 * Получение правильной формы слова в зависимости от числа для русского языка
 *
 * @param count - количество
 * @param one - форма для 1 (например, "штука")
 * @param few - форма для 2-4 (например, "штуки")
 * @param many - форма для 5+ (например, "штук")
 * @returns строка в формате "1 штука", "2 штуки", "5 штук"
 *
 * @example
 * pluralize(1, "штука", "штуки", "штук") // "1 штука"
 * pluralize(2, "штука", "штуки", "штук") // "2 штуки"
 * pluralize(5, "штука", "штуки", "штук") // "5 штук"
 */
export function pluralize(count: number, one: string, few: string, many: string): string {
  if (count % 10 === 1 && count % 100 !== 11) {
    return count.toString() + " " + one;
  } else if (count % 10 >= 2 && count % 10 <= 4 && (count % 100 < 10 || count % 100 >= 20)) {
    return count.toString() + " " + few;
  } else {
    return count.toString() + " " + many;
  }
}

/**
 * Словарь форм для распространённых единиц измерения
 */
const unitForms: Record<string, [string, string, string]> = {
  'шт': ['шт', 'шт', 'шт'],
  'штука': ['шт', 'шт', 'шт'],
  'кг': ['кг', 'кг', 'кг'],
  'килограмм': ['кг', 'кг', 'кг'],
  'г': ['г', 'г', 'г'],
  'грамм': ['г', 'г', 'г'],
  'л': ['л', 'л', 'л'],
  'литр': ['л', 'л', 'л'],
  'мл': ['мл', 'мл', 'мл'],
  'миллилитр': ['мл', 'мл', 'мл'],
  'банка': ['банка', 'банки', 'банок'],
  'банок': ['банка', 'банки', 'банок'],
  'бутылка': ['бутылка', 'бутылки', 'бутылок'],
  'бутылки': ['бутылка', 'бутылки', 'бутылок'],
  'упак': ['упак', 'упак', 'упак'],
  'упаковка': ['упак', 'упак', 'упак'],
  'пачка': ['пачка', 'пачки', 'пачек'],
  'пачки': ['пачка', 'пачки', 'пачек'],
  'пакет': ['пакет', 'пакета', 'пакетов'],
  'пакета': ['пакет', 'пакета', 'пакетов'],
};

/**
 * Форматирует количество с правильной формой единицы измерения
 * Использует предопределённые формы для известных единиц
 *
 * @param count - количество
 * @param unit - единица измерения
 * @returns строка в формате "1 штука", "2 штуки", "5 штук"
 */
export function formatQuantity(count: number, unit: string | null): string {
  if (!unit) return String(count);

  const forms = unitForms[unit];
  if (forms) {
    return pluralize(count, forms[0], forms[1], forms[2]);
  }

  // Если форма не найдена, возвращаем как есть
  return `${count} ${unit}`;
}
